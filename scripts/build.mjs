// Builds the hosted site into dist/ and the editor UI into worker/editor-ui.gen.js.
// src/build.sh does the inlining (mesh data, rigs, gallery, editor), exactly as for the claude.ai artifact; this script runs it
// and then changes two things for the hosted site:
// - the page keeps only the editor's core, plus the edits from site-edits/edits.json baked in as JSON;
// - the editor UI (the part of src/editor.js after the "editor UI" marker) goes into the Worker, which serves it only after login.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const ROOT = path.resolve(path.dirname(new URL(import.meta.url).pathname), '..');
const SRC = path.join(ROOT, 'src'), DIST = path.join(ROOT, 'dist');
// folders the page loads files from, served next to index.html. A new one must be added here (test/build.test.mjs checks).
const STATIC_DIRS = ['photos', 'holdfast', 'mittenmade'];
const MARK = '/* ===== editor UI ===== */';
const ID_OK = /^[\w.:@+~-]{1,200}$/;

// ---------- the page, as the artifact build makes it ----------
execFileSync('sh', [path.join(SRC, 'build.sh')], { stdio: 'inherit' });
let s = fs.readFileSync(path.join(ROOT, 'artifact.html'), 'utf8');

// ---------- editor: core for the page, UI for the Worker ----------
const editor = fs.readFileSync(path.join(SRC, 'editor.js'), 'utf8');
const cut = editor.indexOf(MARK);
if (cut < 0) throw new Error('build: src/editor.js has no "editor UI" marker');
const core = editor.slice(0, cut), ui = editor.slice(cut);
if (/<\/script/i.test(core)) throw new Error('build: the editor core contains a closing script tag');

let edits = {};
const editsFile = path.join(ROOT, 'site-edits', 'edits.json');
if (fs.existsSync(editsFile)) {
  const o = JSON.parse(fs.readFileSync(editsFile, 'utf8'));
  edits = Object.fromEntries(Object.entries(o.edits || {}).filter(([k, v]) => ID_OK.test(k) && v && typeof v === 'object'));
}
// JSON inside a script tag: escape < so no string can close the tag; U+2028/9 for old parsers
const seed = JSON.stringify({ edits }).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');

const whole = '<script>' + editor + '</script>';
const at = s.indexOf(whole);
if (at < 0 || s.indexOf(whole, at + 1) >= 0) throw new Error('build: expected src/build.sh to inline src/editor.js once at the EDITOR placeholder');
s = s.slice(0, at) + `<script id="site-edits" type="application/json">${seed}</script>\n<script>${core}</script>` + s.slice(at + whole.length);

// ---------- visitor flow capture (hosted site only): flow/client.js just before </body> ----------
const flow = fs.readFileSync(path.join(ROOT, 'flow', 'client.js'), 'utf8');
if (/<\/script/i.test(flow)) throw new Error('build: flow/client.js contains a closing script tag');
s += '\n<script>' + flow + '</script>';

// section titles for the flow dashboard: the first heading in each <section data-s="N">
const main = fs.readFileSync(path.join(SRC, 'main.html'), 'utf8');
const sections = [];
for (const m of main.matchAll(/<section\b[^>]*\bdata-s="(\d+)"[^>]*>([\s\S]*?)<\/section>/g)) {
  const h = /<h[1-3]\b[^>]*>([\s\S]*?)<\/h[1-3]>/.exec(m[2]);
  sections[+m[1]] = h ? h[1].replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&[a-z#0-9]+;/g, ' ').replace(/\s+/g, ' ').trim().slice(0, 60) : '';
}
for (let i = 0; i < sections.length; i++) sections[i] = sections[i] || '';

const html = '<!doctype html><html lang="en"><head><meta charset="utf-8">'
  + '<meta name="viewport" content="width=device-width,initial-scale=1,viewport-fit=cover">'
  + '<meta name="description" content="Gabriel Price: wearable and rideable builds, from an ankle exoskeleton to a swerve-drive couch.">'
  + '<style>body{margin:0}</style></head><body>' + s + '</body></html>';

// ---------- write ----------
fs.rmSync(DIST, { recursive: true, force: true });
fs.mkdirSync(DIST, { recursive: true });
fs.writeFileSync(path.join(DIST, 'index.html'), html);
for (const d of STATIC_DIRS) {
  if (fs.existsSync(path.join(ROOT, d))) fs.cpSync(path.join(ROOT, d), path.join(DIST, d), { recursive: true, filter: (f) => !f.endsWith('.DS_Store') });
}
fs.writeFileSync(path.join(ROOT, 'worker', 'sections.gen.js'), '// Generated by scripts/build.mjs from src/main.html. Do not edit.\nexport default ' + JSON.stringify(sections) + ';\n');
fs.writeFileSync(path.join(ROOT, 'worker', 'editor-ui.gen.js'), '// Generated by scripts/build.mjs from src/editor.js. Do not edit.\nexport default ' + JSON.stringify(ui) + ';\n');

const kb = (n) => Math.round(n / 1024) + ' KB';
console.log(`built dist/index.html (${kb(html.length)}), ${Object.keys(edits).length} baked edit(s); editor UI ${kb(ui.length)} → worker/editor-ui.gen.js`);
